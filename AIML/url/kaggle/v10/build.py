"""Merge AIML/url/urlnet_v10.py (serving code) + train_body.py into the single file Kaggle runs: train_url_v10.py."""
from pathlib import Path

HERE = Path(__file__).resolve().parent
shared = (HERE.parents[1] / "urlnet_v10.py").read_text(encoding="utf-8")
body = (HERE / "train_body.py").read_text(encoding="utf-8")
(HERE / "train_url_v10.py").write_text("# GENERATED by build.py - edit AIML/url/urlnet_v10.py or train_body.py instead\n"
                                       + shared + "\n\n" + body, encoding="utf-8")
print("wrote train_url_v10.py")
